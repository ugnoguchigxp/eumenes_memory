function add(
	family: string,
	message: string,
	text: string[],
	gold: Gold[],
	owners: string[] = [],
	negated: number[] = [],
) {
	const id = `N${String(cases.length + 1).padStart(3, "0")}`;
	const items = text.map((value, i) => ({
		itemId: createHash("sha256")
			.update(`${id}:${i}`)
			.digest("hex")
			.slice(0, 20),
		revision: 1,
		subject: (owners[i] ? `other:${owners[i]}` : "self") as
			| "self"
			| `other:${string}`,
		kind: owners[i]
			? ("other_person_note" as const)
			: ("personal_fact" as const),
		subjectLabel: owners[i] || "本人",
		semanticKey: `claim-${i}`,
		value: {
			text: value,
			polarity: negated.includes(i)
				? ("negated" as const)
				: ("affirmed" as const),
		},
	}));
	cases.push({
		id,
		family,
		message,
		items,
		parts: gold.map((g) => ({
			status: g.status,
			requiredIds: g.ids.map((i) => items[i]!.itemId),
			allowedIds: g.ids.map((i) => items[i]!.itemId),
		})),
	});
}
